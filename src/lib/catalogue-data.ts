export function makeSlug(brand: string, model: string, processor: string, display: string): string {
  const raw = `${brand}-${model}-${processor}-${display}-refurbished`;
  return raw
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

